def canonical_road(name: str | None) -> str | None:
    if not name:
        return None
    name = name.strip()
    return ROAD_ALIASES.get(name, name)


def interpolate_freeway(road: str, kilometer: float) -> GeoPoint | None:
    points = FREEWAY_KM.get(canonical_road(road) or road)
    if not points:
        return None
    if kilometer <= points[0][0]:
        _, lat, lng = points[0]
        return GeoPoint(lat, lng, f"{road} {kilometer}k")
    if kilometer >= points[-1][0]:
        _, lat, lng = points[-1]
        return GeoPoint(lat, lng, f"{road} {kilometer}k")
    for (k0, lat0, lng0), (k1, lat1, lng1) in zip(points, points[1:]):
        if k0 <= kilometer <= k1:
            t = 0.0 if k1 == k0 else (kilometer - k0) / (k1 - k0)
            return GeoPoint(
                lat0 + (lat1 - lat0) * t,
                lng0 + (lng1 - lng0) * t,
                f"{road} {kilometer}k",
            )
    return None
